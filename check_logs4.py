import paramiko
def run(cli, cmd):
    i,o,e=cli.exec_command(cmd)
    out=o.read().decode('utf-8','replace').strip()
    err=e.read().decode('utf-8','replace').strip()
    return out, err
c=paramiko.SSHClient()
c.set_missing_host_key_policy(paramiko.AutoAddPolicy())
c.connect('192.168.0.30', username='user', password='******', timeout=10, allow_agent=False, look_for_keys=False)
S='echo 1 | sudo -S '
print('=== /var/log/runit ===')
out,err=run(c, S+'ls -la /mnt/r36s/var/log/runit/ 2>&1')
print(out if out else err)
print('\n=== /var/log/apt 日志 ===')
out,err=run(c, S+'ls -la /mnt/r36s/var/log/apt/ 2>&1')
print(out if out else err)
print('\n=== 找 NetworkManager 相关日志 ===')
out,err=run(c, S+'find /mnt/r36s -iname "*NetworkManager*" -o -iname "*network*.log*" 2>/dev/null | head -20')
print(out if out else err)
print('\n=== run 目录下的服务状态/日志 ===')
out,err=run(c, S+'ls -la /mnt/r36s/run/runit/ 2>&1 | head -20')
print(out if out else err)
print('\n=== /mnt/r36s/home 或用户日志 ===')
out,err=run(c, S+'ls -la /mnt/r36s/root/ 2>&1 | head')
print(out if out else err)
print('\n=== 检查是否有 dmesg/kern 日志 ===')
out,err=run(c, S+'find /mnt/r36s -name "kern*" -o -name "dmesg*" -o -name "messages*" 2>/dev/null | head')
print(out if out else err)
c.close()
print('\nDONE')
