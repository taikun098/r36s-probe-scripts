import paramiko
def run(cli, cmd):
    i,o,e=cli.exec_command(cmd)
    out=o.read().decode('utf-8','replace').strip()
    err=e.read().decode('utf-8','replace').strip()
    return out, err
c=paramiko.SSHClient()
c.set_missing_host_key_policy(paramiko.AutoAddPolicy())
c.connect('192.168.0.30', username='user', password='******', timeout=10, allow_agent=False, look_for_keys=False)
S='echo 1 | sudo -S '
print('=== 挂载状态 ===')
out,err=run(c, S+'findmnt | grep sdb2')
print(out if out else err)
print('\n=== 重新挂载 sdb2 ===')
out,err=run(c, S+'mkdir -p /mnt/r36s && mount /dev/sdb2 /mnt/r36s 2>&1; echo M=$?')
print(out if out else err)
print('\n=== /mnt/r36s 顶层 ===')
out,err=run(c, S+'ls /mnt/r36s')
print(out if out else err)
print('\n=== /mnt/r36s/var ===')
out,err=run(c, S+'ls /mnt/r36s/var 2>&1')
print(out if out else err)
print('\n=== btrfs 子卷 ===')
out,err=run(c, S+'btrfs subvolume list /mnt/r36s 2>&1 | head -20')
print(out if out else err)
print('\n=== 找日志文件 ===')
out,err=run(c, S+'find /mnt/r36s -maxdepth 3 -name "syslog*" -o -name "dmesg*" -o -name "*.log" 2>/dev/null | head -20')
print(out if out else err)
c.close()
print('\nDONE')
